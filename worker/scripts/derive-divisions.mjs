// One-off: parse the org directory CSV and derive, per Division, the single
// highest-RANK person as that division's head (anh Luân's call 06-15: auto从
// rank). Emits SQL seed for the `division` + `user_division` tables and prints
// a review table. Re-runnable; pure (no Date.now / random).
//
//   node worker/scripts/derive-divisions.mjs            # print review + SQL
//   node worker/scripts/derive-divisions.mjs --sql-only # SQL only (for piping)
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
// CSV lives one level above the excalidraw repo (the org export).
const CSV = resolve(__dirname, "../../../user.csv");

// Korean corporate rank ladder, high → low. Higher weight = more senior.
// Group/board ranks at top; project 직책 (실장/소장) mid; staff grades bottom.
const RANK = {
  이사장: 100, // board chairman
  회장: 96, // chairman
  부회장: 92, // vice chairman
  사장: 88, // president
  부사장: 84, // executive VP
  고문: 80, // senior advisor
  전문위원: 78, // expert advisor
  전무: 74, // senior managing director
  상무: 70, // managing director
  이사: 66, // director
  이사대우: 64, // director-equivalent
  실장: 58, // office head
  "소장(S1)": 54,
  "소장(S2)": 52,
  소장: 50,
  팀장: 46, // team leader
  부팀장: 42, // deputy team leader
  부장: 40, // general manager
  차장: 36, // deputy general manager
  과장: 32, // manager
  대리: 28, // assistant manager
  "6급사원": 16,
  "5급사원: ": 14,
  "5급사원": 14,
  "4급사원": 12,
};

const slug = (name) =>
  "div-" +
  name
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const sqlStr = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const raw = readFileSync(CSV, "utf8");
const lines = raw.split(/\r?\n/).filter((l) => l.trim().length);
const header = lines.shift(); // 순 번,사원명,소속,부서,Division,직급,email

const unknownRanks = new Set();
const skipped = [];
const byDivision = new Map(); // division name -> { members:[], head }

for (const line of lines) {
  const parts = line.split(",");
  if (parts.length < 7) {
    skipped.push(line);
    continue;
  }
  // Fixed schema: 순번,name,소속,부서,Division,직급,email (email is last).
  const seq = parseInt(parts[0], 10);
  const division = parts[4].trim();
  const rank = parts[5].trim();
  const email = parts[6].trim().toLowerCase();
  if (!division || !email) {
    skipped.push(line);
    continue;
  }
  const weight = RANK[rank];
  if (weight === undefined) {
    unknownRanks.add(rank);
  }
  if (!byDivision.has(division)) {
    byDivision.set(division, { members: [] });
  }
  byDivision.get(division).members.push({
    seq,
    rank,
    email,
    weight: weight ?? 0,
  });
}

// Head = max weight; tie-break by lowest 순번 (stable, deterministic). Deputy =
// the NEXT person down (rank 2) — anh Luân 06-15: "cấp dưới liền kề của người
// đứng đầu phòng ban" also gets project-create rights.
for (const [, d] of byDivision) {
  d.members.sort((a, b) => b.weight - a.weight || a.seq - b.seq);
  d.head = d.members[0];
  d.deputy = d.members[1] ?? null;
}

const sqlOnly = process.argv.includes("--sql-only");
// --deputies: emit ONLY the deputy UPDATEs (for the additive 0024 migration,
// since the division rows already exist from 0022).
if (process.argv.includes("--deputies")) {
  const lines = [
    "-- AUTO-GENERATED by derive-divisions.mjs --deputies — deputy = rank 2.",
  ];
  for (const [name, d] of [...byDivision].sort()) {
    if (!d.deputy) {
      continue;
    }
    lines.push(
      `UPDATE division SET deputy_email = ${sqlStr(d.deputy.email)} ` +
        `WHERE id = ${sqlStr(slug(name))};`,
    );
  }
  process.stdout.write(lines.join("\n") + "\n");
  process.exit(0);
}

if (!sqlOnly) {
  console.error(`\nDivisions: ${byDivision.size}  (CSV rows: ${lines.length})`);
  if (skipped.length) {
    console.error(`SKIPPED ${skipped.length} malformed rows:`);
    skipped.forEach((s) => console.error("  " + s));
  }
  if (unknownRanks.size) {
    console.error(`UNKNOWN RANKS (weight 0): ${[...unknownRanks].join(", ")}`);
  }
  console.error("\nDivision → head (rank):");
  for (const [name, d] of [...byDivision].sort()) {
    console.error(
      `  ${name.padEnd(34)} ${d.head.email.padEnd(34)} ${d.head.rank} ` +
        `(${d.members.length} ppl)`,
    );
  }
  console.error("");
}

// ---- SQL seed -------------------------------------------------------------
const out = [];
out.push("-- AUTO-GENERATED by worker/scripts/derive-divisions.mjs — do not");
out.push("-- hand-edit; re-run the script. Heads derived from highest 직급.");
out.push("");
for (const [name, d] of [...byDivision].sort()) {
  const id = slug(name);
  out.push(
    `INSERT OR IGNORE INTO division (id, name, head_email) VALUES ` +
      `(${sqlStr(id)}, ${sqlStr(name)}, ${sqlStr(d.head.email)});`,
  );
}
out.push("");
for (const [name, d] of [...byDivision].sort()) {
  const id = slug(name);
  for (const m of d.members) {
    out.push(
      `INSERT OR IGNORE INTO user_division (email, division_id) VALUES ` +
        `(${sqlStr(m.email)}, ${sqlStr(id)});`,
    );
  }
}
process.stdout.write(out.join("\n") + "\n");

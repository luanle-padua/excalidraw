// One-off: seed the "Overseas Subsidiary Vietnam Corporation" division + its
// staff (anh Luân 06-16). Creates/updates Supabase Auth users (Korean name +
// 직급 matching the DB rank vocabulary) and EMITS the D1 SQL for the
// division + user_division tables (head = highest rank = 이정호 부사장).
//
//   node scripts/seed-vietnam-subsidiary.mjs --dry   # parse + show, no writes
//   node scripts/seed-vietnam-subsidiary.mjs         # create/update for real
//
// Then apply the printed D1 seed (written to worker/scripts/seed-vietnam-division.sql):
//   cd worker && npx wrangler d1 execute mcm-db --local --file ./scripts/seed-vietnam-division.sql

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { createClient } from "@supabase/supabase-js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DRY = process.argv.includes("--dry");
const DEFAULT_PASSWORD = "MapMeet@2026";

const DIVISION = "Overseas Subsidiary Vietnam Corporation";
const COMPANY = "Overseas Subsidiary Vietnam Corporation";

// Kim Won-jik / "Executive Director" intentionally OMITTED — the English title
// has no clean single 직급 match in the DB ladder (전무/상무/이사), anh Luân:
// "cái nào k có thì bỏ user đó đi".
const PEOPLE = [
  { name: "이정호", title: "부사장", email: "ljho@mapgroup.co.kr", empNo: "VN1" },
  { name: "장현석", title: "소장(S1)", email: "ajanghs7@mapgroup.co.kr", empNo: "VN2" },
  { name: "김진아", title: "소장(S2)", email: "김진아@mapgroup.co.kr", empNo: "VN3" },
  { name: "안", title: "4급사원", email: "an@mapgroup.co.kr", empNo: "VN4" },
];

// Head = the single highest-rank person (부사장). Hard-coded here since this is
// a tiny fixed set; mirrors derive-divisions.mjs's "max 직급 weight" rule.
const HEAD_EMAIL = "ljho@mapgroup.co.kr";

const slug = (name) =>
  "div-" +
  name
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
const sqlStr = (s) => "'" + String(s).replace(/'/g, "''") + "'";

// ---- emit D1 seed (division + user_division) ------------------------------
const divId = slug(DIVISION);
const sql = [
  "-- AUTO-GENERATED by scripts/seed-vietnam-subsidiary.mjs.",
  `INSERT OR IGNORE INTO division (id, name, head_email) VALUES (${sqlStr(
    divId,
  )}, ${sqlStr(DIVISION)}, ${sqlStr(HEAD_EMAIL)});`,
  `UPDATE division SET head_email = ${sqlStr(
    HEAD_EMAIL,
  )} WHERE id = ${sqlStr(divId)};`,
  ...PEOPLE.map(
    (p) =>
      `INSERT OR IGNORE INTO user_division (email, division_id) VALUES (${sqlStr(
        p.email.toLowerCase(),
      )}, ${sqlStr(divId)});`,
  ),
];
const sqlPath = join(__dirname, "..", "worker", "scripts", "seed-vietnam-division.sql");
writeFileSync(sqlPath, sql.join("\n") + "\n");
console.log(`D1 seed written → ${sqlPath}\n`);
console.log(sql.join("\n"));
console.log(
  `\nApply: cd worker && npx wrangler d1 execute mcm-db --local --file ./scripts/seed-vietnam-division.sql\n`,
);

// ---- creds (worker/.dev.vars) ---------------------------------------------
const env = {};
for (const line of readFileSync(
  join(__dirname, "..", "worker", ".dev.vars"),
  "utf8",
).split(/\r?\n/)) {
  const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
  if (m) {
    env[m[1]] = m[2];
  }
}
const SUPABASE_URL = env.SUPABASE_URL;
const SERVICE_KEY = env.SUPABASE_SERVICE_API_KEY || env.SUPABASE_SERVICE_ROLE_KEY;
if (!SUPABASE_URL || !SERVICE_KEY) {
  console.error("Missing SUPABASE_URL / SUPABASE_SERVICE_API_KEY in worker/.dev.vars");
  process.exit(1);
}

console.log(
  `Supabase: ${DRY ? "DRY — no writes" : "creating/updating " + PEOPLE.length + " users"}`,
);
for (const p of PEOPLE) {
  console.log(`  ${p.email.padEnd(28)} ${p.name} / ${p.title}`);
}
if (DRY) {
  process.exit(0);
}

const admin = createClient(SUPABASE_URL, SERVICE_KEY, {
  auth: { autoRefreshToken: false, persistSession: false },
});

// map existing users by email
const existing = new Map();
for (let page = 1; page <= 50; page++) {
  const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 1000 });
  if (error) {
    console.error("listUsers failed:", error.message);
    process.exit(1);
  }
  for (const u of data.users) {
    if (u.email) {
      existing.set(u.email.toLowerCase(), u);
    }
  }
  if (data.users.length < 1000) {
    break;
  }
}

const meta = (p) => ({
  name: p.name,
  display_name: p.name,
  title: p.title,
  division: DIVISION,
  department: DIVISION,
  company: COMPANY,
  emp_no: p.empNo,
});

let created = 0, updated = 0, failed = 0;
for (const p of PEOPLE) {
  const email = p.email.toLowerCase();
  const ex = existing.get(email);
  try {
    if (ex) {
      const { error } = await admin.auth.admin.updateUserById(ex.id, {
        user_metadata: { ...(ex.user_metadata ?? {}), ...meta(p) },
      });
      if (error) {
        throw error;
      }
      updated++;
      console.log(`✓ updated ${email}`);
    } else {
      const { error } = await admin.auth.admin.createUser({
        email,
        password: DEFAULT_PASSWORD,
        email_confirm: true,
        user_metadata: meta(p),
      });
      if (error) {
        throw error;
      }
      created++;
      console.log(`✓ created ${email}`);
    }
  } catch (e) {
    failed++;
    console.error(`✗ ${email}: ${e.message ?? e}`);
  }
}

console.log(`\nDone. created=${created} updated=${updated} failed=${failed}`);
console.log(`Default password: ${DEFAULT_PASSWORD}`);
